export type TranslationKey = keyof typeof translations.fr;

export function t(key: TranslationKey, lang: Lang): string {
  return (translations[lang] as Record<string, string>)[key]
    ?? (translations.fr as Record<string, string>)[key]
    ?? key;
}

export function photosTakenLabel(count: number, lang: Lang): string {
  if (count <= 1) return t('photos_taken_one', lang);
  return t('photos_taken_many', lang).replace('{n}', String(count));
}

export function getLangFromProp(langProp: string | undefined | null): Lang {
  const code = (langProp ?? '').toLowerCase().slice(0, 2);
  if (code === 'en') return 'en';
  if (code === 'nb' || code === 'no' || code === 'nn') return 'no';
  return 'fr';
}
